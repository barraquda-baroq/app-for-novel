export interface ToolAnnotations {
  title: string
  readOnlyHint: boolean
  destructiveHint: boolean
  idempotentHint: boolean
  openWorldHint: boolean
}

export interface ToolDef {
  name: ToolName
  title: string
  description: string
  kind: 'read' | 'write' | 'trash'
  annotations: ToolAnnotations
}

const read = (name: ToolName, title: string, description: string): ToolDef => ({
  name,
  title,
  description,
  kind: 'read',
  annotations: { title, readOnlyHint: true, destructiveHint: false, idempotentHint: true, openWorldHint: false },
})

const write = (name: ToolName, title: string, description: string): ToolDef => ({
  name,
  title,
  description,
  kind: 'write',
  annotations: { title, readOnlyHint: false, destructiveHint: false, idempotentHint: true, openWorldHint: false },
})

const trash = (name: ToolName, title: string, description: string): ToolDef => ({
  name,
  title,
  description,
  kind: 'trash',
  annotations: { title, readOnlyHint: false, destructiveHint: true, idempotentHint: true, openWorldHint: false },
})

